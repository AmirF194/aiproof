def main() -> None:
    seen = set()
    for r in ROLES:
        if r[0] in seen:
            raise SystemExit(f"Duplicate role: {r[0]}")
        seen.add(r[0])

    rows = []
    for name, cat, d, a, s, st, lo, hi, trend in ROLES:
        sc = score_of(d, a, s, st)
        rows.append((name, cat, d, a, s, st, sc, lo, hi, trend, tier(sc)))

    rows.sort(key=lambda r: (-r[6], r[1], r[0]))

    with CSV_PATH.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow([
            "role", "category", "demand", "automation_resistance", "skill_depth",
            "strategic_importance", "score", "salary_low_usd", "salary_high_usd",
            "demand_trend", "verdict_tier",
        ])
        w.writerows(rows)

    print(f"wrote {len(rows)} roles to {CSV_PATH}")


if __name__ == "__main__":
    main()
