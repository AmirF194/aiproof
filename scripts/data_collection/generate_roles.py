# Mirror scripts/analysis/_common.py — keep formula and tier bands in sync.
TIER_BANDS = [
    ("fortress", 83, 101),
    ("safe",     70, 83),
    ("stable",   58, 70),
    ("exposed",  41, 58),
    ("at_risk",   0, 41),
]


def _round_half_up(x: float) -> int:
    return int(math.floor(x + 0.5 + 1e-9))


def score_of(d: int, a: int, s: int, st: int) -> int:
    raw = d * 0.30 + a * 0.35 + s * 0.15 + st * 0.20
    return _round_half_up(raw * 10)


def tier(score_value: int) -> str:
    for name, lo, hi in TIER_BANDS:
        if lo <= score_value < hi:
            return name
    return "fortress" if score_value >= 100 else "at_risk"


